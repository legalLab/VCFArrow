#' @title vcf2migrate
#'
#' @description
#' Converts a VCFArrow object to a MIGRATE-N format infile
#'
#' @author Tomas Hrbek May 2026
#'
#' @param vcf_arrow -> VCFArrow object
#' @param out_file -> name of file to output, no default (character)
#' @param keep_groups -> groups to retain, default NULL (character)
#' @param block_size -> number of SNPs (method S) or base pairs (method N) per
#'   linked block, default 100 (integer)
#' @param method -> "C" (allele counts, HapMap format), "S" (sequences, loci
#'   of block_size SNPs, "(sK)") or "N" (SNPs, loci of block_size bp per
#'   CHROM, "(nK)"), default "S" (character)
#'
#' @return Invisibly returns the input VCFArrow object; called for its side effect of writing `out_file`.
#'
#' @details
#' This function converts a VCFArrow object to an external MIGRATE-N formatted file.
#' Writing occurs in chunks whose size is determined by the read_vcf() function.
#' Larger chunks result in faster writing speeds.
#' If no groups are defined, the default behavior is to use all groups.
#' The data file follows the Migrate-N manual (section 4, "Data file
#' specification",
#' <https://peterbeerli.com/downloads/migrate/docs/migratedoc.pdf>).
#' Method "S" writes sequence data: each sample as two haplotypes
#' (<name>_1, <name>_2) of the SNPs' nucleotides ('?' if missing), cut into
#' loci of block_size consecutive SNPs, labelled "(sK)" (a sequence locus of
#' K sites).
#' Method "N" writes the same sequences cut into loci of the SNPs on one
#' CHROM within the same interval of block_size bp, labelled "(nK)" (K linked
#' SNPs), with the data type N (SNPs) on the first line.
#' Method "C" writes the allele counts of each population in Migrate-N's
#' HapMap format (data type H): for each SNP its position, REF and ALT
#' nucleotides with their counts, and the total; the manual describes this
#' format as preliminary.  SNPs without called alleles in some population are
#' left out (with a warning), as Migrate-N cannot compute their allele
#' frequencies there.
#' The first line gives the number of populations and of loci.  Individual
#' names are written in a fixed field of 10 characters, Migrate-N's default;
#' if longer names are needed, a warning gives the nmlength to set in the
#' parmfile.  Population names must not start with a number.
#' Whether loci of SNPs should be treated as linked depends on whether the
#' SNPs were mapped (so that linkage is known) or called de novo.
#'
#' @examples
#' f <- system.file("extdata", "vaillantii_discosnp_sub.vcf.gz",
#'                  package = "VCFArrow")
#' vcf <- read_vcf(f) |> set_vcf_groups(dirname(f))
#' vcf2migrate(vcf, out_file = tempfile(fileext = ".txt"))
#'
#' @export
#'

# method = "C"  (allele counts, population-level)
#   Format:  n_pops n_loci
#            max_obs pop_name
#            ref_count alt_count   (one line per variant)
#
# method = "S"  (nucleotide sequences, individual-level, fixed blocks)
#   Alleles are written as single nucleotide characters (REF or ALT).
#   Haplotypes are concatenated into a sequence string per line.
#   Block header uses (s{block_size}) for full blocks and (n{r}) for the
#   last partial block.  Missing allele: "?".
#
# method = "N"  (nucleotide sequences, individual-level, chromosome intervals)
#   Same output structure as "S" but block sizes are computed from CHROM/POS:
#   each block spans block_size bp within a chromosome.  All block labels
#   use (s{count}) regardless of whether the last interval is partial.

vcf2migrate <- function(vcf_arrow, out_file, keep_groups = NULL,
                        block_size = 100L, method = c("S", "N", "C")) {

  if (missing(out_file)) cli::cli_abort("{.arg out_file} must be supplied.")

  method <- match.arg(method)
  setup <- .vcf_export_setup(vcf_arrow, keep_groups)

  # Migrate-N: population names must not start with a number
  bad <- grepl("^[0-9]", setup$group_names)
  if (any(bad))
    cli::cli_abort(c(
      "Migrate-N population names must not start with a number.",
      "x" = "Group label{?s}: {.val {setup$group_names[bad]}}"
    ))
  title <- "Generated by VCFArrow"

  if (method == "C") {
    acc <- .accumulate_pops_lowmem(setup, "Migrate-N (C)")

    # Migrate-N computes allele frequencies per population, and crashes on
    # SNPs without called alleles in a population (0/0): such SNPs are left
    # out
    ok <- colSums(acc$nobs == 0L) == 0L
    if (!any(ok))
      cli::cli_abort("No SNP has called alleles in every population.")
    if (!all(ok))
      cli::cli_warn(
        "{sum(!ok)} SNP{?s} without called alleles in some population left out \\
         (Migrate-N cannot use them)."
      )

    cli::cli_alert_info("Writing Migrate-N ({method}) file: {sum(ok)} SNP{?s}...")

    write_migrate_cpp(acc$ref[, ok, drop = FALSE], acc$alt[, ok, drop = FALSE],
                      acc$nobs[, ok, drop = FALSE], setup$group_names,
                      setup$group_sizes, as.numeric(setup$variants$POS[ok]),
                      setup$variants$REF[ok], setup$variants$ALT[ok], title, out_file)
  } else {
    acc <- .accumulate_individuals(setup, paste0("Migrate-N (", method, ")"))

    # Locus labels (line 2), one per block, in the order the sequences are
    # written: "(sK)" (sequence locus) for method S, "(nK)" (K linked SNPs)
    # for method N, K being the number of SNPs in the block.
    # Method S: blocks of block_size consecutive SNPs (the last may be
    #   smaller).
    # Method N: a block is a run of consecutive SNPs on one CHROM within the
    #   same interval of block_size bp, the interval being
    #   (POS - smallest POS of the CHROM) %/% block_size.  Counting per
    #   (CHROM, interval) group instead would list the blocks in sorted CHROM
    #   order, not matching the sequences when the CHROMs are not sorted.
    n_var <- setup$n_var
    block_size <- as.integer(block_size)

    if (method == "S") {
      n_full <- n_var %/% block_size
      remainder <- n_var %% block_size
      sizes <- c(rep(block_size, n_full), if (remainder > 0L) remainder)
      block_labels <- paste0("(s", sizes, ")")
      datatype <- ""  # sequence data: data type left to the parmfile
    } else {  # method == "N"
      v <- setup$variants
      o <- order(v$CHROM, v$POS, method = "radix")
      first <- !duplicated(v$CHROM[o])
      min_pos <- v$POS[o][first][match(v$CHROM, v$CHROM[o][first])]
      interval <- (v$POS - min_pos) %/% block_size
      block_labels <- paste0("(n", rle(paste(v$CHROM, interval, sep = "\r"))$lengths, ")")
      datatype <- "N"  # SNP data (nucleotide polymorphisms)
    }

    # individual names are read from a fixed field of nmlength characters
    # (default 10); each sample is written as two haplotypes, <name>_1 and
    # <name>_2
    name_width <- max(10L, nchar(setup$samples, type = "bytes") + 2L)
    if (name_width > 10L)
      cli::cli_warn(c(
        "Sample names (with the suffix _1/_2) are up to {name_width} characters \\
         long; Migrate-N reads 10 by default.",
        "i" = "Set {.code nmlength={name_width}} in the Migrate-N parmfile."
      ))

    cli::cli_alert_info(
      "Writing Migrate-N ({method}) file: {length(block_labels)} loc{?us/i}..."
    )

    write_migrate_seq_cpp(
      acc$a1, acc$a2,
      setup$variants$REF, setup$variants$ALT,
      setup$samples, setup$group_names, setup$group_sizes,
      block_labels, datatype, title, name_width, out_file
    )
  }

  cli::cli_alert_success("Migrate-N file written to {.file {out_file}}")

  invisible(vcf_arrow)
}
